#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Merge streaming WebVTT (per-chunk) into sentence-level lines.

Input (generated by `streaming_vlm/inference/inference.py`) looks like:
    00:00:00.000 --> 00:00:01.000
     Infer Time: 0.123s
     match has taken ...

Output (txt) format:
    00:00:00.000 --> 00:00:09.000 match has taken place, in which ...
One line per (approx.) sentence. Time range is aligned to chunk boundaries.
"""

from __future__ import annotations

import argparse
import os
import re
from dataclasses import dataclass
from typing import Iterable, Iterator, List, Optional, Tuple

def sec2ts(sec: float) -> str:
    h, rem = divmod(int(sec), 3600)
    m, s = divmod(rem, 60)
    ms = int((sec - int(sec)) * 1000)
    return f"{h:02d}:{m:02d}:{s:02d}.{ms:03d}"


_TS_LINE_RE = re.compile(
    r"^(?P<start>\d{2}:\d{2}:\d{2}\.\d{3})\s+-->\s+(?P<end>\d{2}:\d{2}:\d{2}\.\d{3})(?:\s+.*)?$"
)

_TRAILING_ELLIPSIS_RE = re.compile(r"(?:\s*(?:\.\.\.|…)+)\s*$")
_WS_RE = re.compile(r"\s+")

_ABBREVIATIONS = {
    "mr",
    "mrs",
    "ms",
    "dr",
    "prof",
    "sr",
    "jr",
    "st",
    "vs",
    "etc",
    "e.g",
    "i.e",
    "u.s",
    "u.k",
    "a.m",
    "p.m",
}

_SENT_END_CHARS = {".", "!", "?", "。", "！", "？"}
_CLOSERS = {'"', "'", "”", "’", ")", "]", "}", "」", "』", "】", "）"}


def _ts_to_seconds(ts: str) -> float:
    hh, mm, rest = ts.split(":", 2)
    ss, ms = rest.split(".", 1)
    return int(hh) * 3600 + int(mm) * 60 + int(ss) + int(ms) / 1000.0


def _clean_chunk_text(text: str) -> str:
    text = text.strip()
    if not text:
        return ""
    text = _TRAILING_ELLIPSIS_RE.sub("", text).strip()
    text = _WS_RE.sub(" ", text).strip()
    return text


def _dedupe_overlap(prev_text: str, new_text: str) -> str:
    prev_text = _WS_RE.sub(" ", (prev_text or "")).strip()
    new_text = _WS_RE.sub(" ", (new_text or "")).strip()
    if not prev_text or not new_text:
        return new_text

    prev_tokens = re.findall(r"\S+", prev_text)
    new_tokens = re.findall(r"\S+", new_text)
    max_k = min(len(prev_tokens), len(new_tokens), 20)
    for k in range(max_k, 0, -1):
        if prev_tokens[-k:] == new_tokens[:k]:
            return " ".join(new_tokens[k:]).strip()

    prev_tail = prev_text[-200:]
    max_len = min(len(prev_tail), len(new_text))
    for n in range(max_len, 4, -1):
        if prev_tail.endswith(new_text[:n]):
            return new_text[n:].lstrip()
    return new_text


def _is_sentence_end(text: str, idx: int) -> bool:
    ch = text[idx]
    if ch in {"。", "！", "？", "!", "?"}:
        return True
    if ch != ".":
        return False

    if idx + 1 < len(text) and text[idx + 1] == ".":
        return False

    if 0 < idx < len(text) - 1 and text[idx - 1].isdigit() and text[idx + 1].isdigit():
        return False

    m = re.search(r"(\b[\w]+)$", text[:idx])
    if m and m.group(1).lower() in _ABBREVIATIONS:
        return False

    return True


def _split_complete_sentences(text: str) -> Tuple[List[str], str]:
    sentences: List[str] = []
    buf = text

    while True:
        end_idx: Optional[int] = None
        for i, _ch in enumerate(buf):
            if _ch in _SENT_END_CHARS and _is_sentence_end(buf, i):
                end = i + 1
                while end < len(buf) and buf[end] in _CLOSERS:
                    end += 1
                end_idx = end
                break

        if end_idx is None:
            return sentences, buf

        sentence = buf[:end_idx].strip()
        if sentence:
            sentences.append(sentence)
        buf = buf[end_idx:].lstrip()


@dataclass
class SentenceAccumulator:
    buffer: str = ""
    start_time_s: Optional[float] = None
    tail: str = ""

    def add_chunk(self, chunk_start_s: float, chunk_end_s: float, chunk_text: str) -> List[Tuple[float, float, str]]:
        chunk_text = _clean_chunk_text(chunk_text)
        if not chunk_text:
            return []

        ref = self.buffer if self.buffer else self.tail
        chunk_text = _dedupe_overlap(ref, chunk_text).strip()
        if not chunk_text:
            return []

        if self.start_time_s is None:
            self.start_time_s = chunk_start_s

        if self.buffer and not self.buffer.endswith(" ") and not chunk_text.startswith(
            (",", ".", "!", "?", ":", ";", "，", "。", "！", "？", "：", "；")
        ):
            self.buffer += " "
        self.buffer += chunk_text

        self.tail = (self.tail + " " + chunk_text).strip()[-500:]

        sentences, remainder = _split_complete_sentences(self.buffer)
        outputs: List[Tuple[float, float, str]] = []
        if sentences:
            for sent in sentences:
                outputs.append((float(self.start_time_s), float(chunk_end_s), sent))
                self.start_time_s = chunk_end_s
            self.buffer = remainder.lstrip()
            if not self.buffer:
                self.start_time_s = None
        return outputs

    def flush(self, final_end_s: float) -> Optional[Tuple[float, float, str]]:
        if not self.buffer.strip() or self.start_time_s is None:
            return None
        sent = self.buffer.strip()
        self.buffer = ""
        start = float(self.start_time_s)
        self.start_time_s = None
        return (start, float(final_end_s), sent)


def _iter_vtt_cues(path: str) -> Iterator[Tuple[float, float, str]]:
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().splitlines()

    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if not line or line == "WEBVTT":
            continue

        m = _TS_LINE_RE.match(line)
        if not m:
            continue

        start_s = _ts_to_seconds(m.group("start"))
        end_s = _ts_to_seconds(m.group("end"))

        payload: List[str] = []
        while i < len(lines) and lines[i].strip() != "":
            pl = lines[i].strip()
            if not pl.lower().startswith("infer time:"):
                payload.append(pl)
            i += 1

        yield (start_s, end_s, " ".join(payload).strip())


def merge_vtt_to_sentence_lines(input_vtt: str, output_txt: str, flush_last: bool = True) -> None:
    os.makedirs(os.path.dirname(output_txt) or ".", exist_ok=True)
    acc = SentenceAccumulator()
    last_end: Optional[float] = None

    with open(output_txt, "w", encoding="utf-8") as out:
        for start_s, end_s, chunk_text in _iter_vtt_cues(input_vtt):
            last_end = end_s
            for s_start, s_end, sent in acc.add_chunk(start_s, end_s, chunk_text):
                out.write(f"{sec2ts(s_start)} --> {sec2ts(s_end)} {sent}\n")

        if flush_last and last_end is not None:
            flushed = acc.flush(last_end)
            if flushed is not None:
                s_start, s_end, sent = flushed
                out.write(f"{sec2ts(s_start)} --> {sec2ts(s_end)} {sent}\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    file_dir = "streaming-vlm/streaming_vlm/inference/"
    input_file = os.path.join(file_dir, "result.vtt")
    output_file = os.path.join(file_dir, "result_merged.txt")
    ap.add_argument("--input", "-i", default=input_file, help="Input .vtt path")
    ap.add_argument("--output", "-o", default=output_file, help="Output .txt path (default: input basename + .txt)")
    ap.add_argument("--no_flush_last", action="store_true", help="Do not flush the last incomplete sentence")
    args = ap.parse_args()

    output = args.output
    if output is None:
        base, _ = os.path.splitext(args.input)
        output = base + ".txt"

    merge_vtt_to_sentence_lines(args.input, output, flush_last=not args.no_flush_last)
    print(f"Saved: {output}")


if __name__ == "__main__":
    main()
