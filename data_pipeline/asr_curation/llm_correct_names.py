@dataclass
class LLMConfig:
    """Configuration for LLM API calls."""
    api_base: str
    model: str
    temperature: float
    max_tokens: int
    timeout: float
    max_retries: int
    retry_delay: float
    request_delay: float
    max_verification_rounds: int  # Max rounds for iterative verification


@dataclass
class ProcessingStats:
    """Statistics for name correction processing."""
    total_segments: int = 0
    processed_segments: int = 0
    segments_with_corrections: int = 0
    total_corrections: int = 0
    segments_with_unknown_mentions: int = 0
    total_unknown_mentions: int = 0
    api_errors: int = 0
    
    def print_summary(self) -> None:
        print(f"\n{'='*60}")
        print("Processing Summary:")
        print(f"  Total segments: {self.total_segments}")
