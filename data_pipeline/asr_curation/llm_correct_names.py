#!/usr/bin/env python3
"""Use Qwen3 to correct player/coach/referee names in ASR transcription segments.

This script processes ASR annotations with a local LLM:
1. Extract all person names from metadata (players, coaches, referees)
2. For each segment with 'llm_polished_text', identify and correct names
3. Add 'name_corrections' field (list of "Wrong->Correct" strings)
4. Add 'corrected_text' field (text with corrected names in [brackets])
5. Add 'unknown_person_mentions' field (list of person names mentioned but not in metadata)

Two-round verification:
  - Round 1: Identify potential name errors and suggest corrections
  - Round 2: Verify corrections with reasoning (reasoning not saved)

For swift deployment (http://localhost:8000/v1/chat/completions):
  python llm_correct_names.py \
    --input-root /path/to/SoccerNet/asr/annos_cleaned \
    --api-base http://localhost:8000/v1 \
    --model Qwen/Qwen2.5-72B-Instruct \
    --limit 5
"""

